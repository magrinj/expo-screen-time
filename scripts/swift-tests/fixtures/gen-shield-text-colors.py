#!/usr/bin/env python3
"""Reference implementation of the shield's default text colours (a third,
independent one): regenerates shield-text-colors.tsv, which the Kotlin
(ShieldTextColorsSwiftParityTest) and Swift (scripts/swift-tests/main.swift)
tests both read. Edit the CASES, run this, commit both files."""

def parse(s):
    if s == "-":
        return None
    d = s.strip().lstrip("#")
    if not d or any(c not in "0123456789abcdefABCDEF" for c in d) or len(d) not in (6, 8):
        return None
    v = int(d, 16)
    if len(d) == 6:
        return (v >> 16 & 255, v >> 8 & 255, v & 255, 255)
    return (v >> 24 & 255, v >> 16 & 255, v >> 8 & 255, v & 255)

def hexa(c):
    if c is None:
        return "-"
    r, g, b, a = c
    return "#%02X%02X%02X" % (r, g, b) if a == 255 else "#%02X%02X%02X%02X" % (r, g, b, a)

def lin(c):
    c /= 255
    return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4

def lum(c):
    return 0.2126 * lin(c[0]) + 0.7152 * lin(c[1]) + 0.0722 * lin(c[2])

def contrast(a, b):
    la, lb = lum(a), lum(b)
    return (max(la, lb) + 0.05) / (min(la, lb) + 0.05)

WHITE, BLACK = (255, 255, 255, 255), (0, 0, 0, 255)

def on_background(bg):
    return WHITE if contrast(WHITE, bg) >= contrast(BLACK, bg) else BLACK

def mix(fg, bg, percent):
    return tuple((percent * f + (100 - percent) * b + 50) // 100 for f, b in zip(fg[:3], bg[:3])) + (255,)

def secondary_on(bg):
    fg = on_background(bg)
    for p in range(70, 101, 5):
        c = mix(fg, bg, p)
        if contrast(c, bg) >= 3.0:
            return c
    return fg

def resolve(bg, title, subtitle, button_bg, button, secondary):
    return (
        title or (on_background(bg) if bg else None),
        subtitle or (secondary_on(bg) if bg else None),
        button or (on_background(button_bg) if button_bg else None),
        secondary or (on_background(bg) if bg else None),
    )

# background, title, subtitle, primaryButton.backgroundColor, primaryButton.color, secondaryButton.color
CASES = [
    ("no background: every default stays the platform's", "-", "-", "-", "-", "-", "-"),
    ("the example app's dark background, no text colours", "#1a1a2e", "-", "-", "-", "-", "-"),
    ("the example app exactly: dark background, blue button", "#1a1a2e", "-", "-", "#4a4ae8", "-", "-"),
    ("a white background", "#FFFFFF", "-", "-", "-", "-", "-"),
    ("a light amber background and button", "#FFD54F", "-", "-", "#FFD54F", "-", "-"),
    ("a mid grey, where 70% is not enough for the subtitle", "#808080", "-", "-", "-", "-", "-"),
    ("a saturated mid blue", "#1A73E8", "-", "-", "-", "-", "-"),
    ("a saturated red", "#E53935", "-", "-", "-", "-", "-"),
    ("explicit colours win, even unreadable ones", "#000000", "#111111", "#222222", "#000000", "#101010", "#121212"),
    ("a translucent background is judged by its RGB", "#1a1a2e80", "-", "-", "-", "-", "-"),
    ("a button background with no shield background", "-", "-", "-", "#FFD54F", "-", "-"),
    ("a dark button on a light shield", "#F5F5F5", "-", "-", "#1C1B1F", "-", "-"),
    ("an explicit subtitle, default title", "#1a1a2e", "-", "#aaaaaa", "-", "-", "-"),
    ("an unparsable colour counts as unset", "#1a1a2e", "blue", "#12345", "-", "-", "-"),
    ("legacy 8-digit colours: alpha on the title is kept as given", "#FFFFFF", "#00000080", "-", "-", "-", "-"),
    ("near-black background", "#0D1B2A", "-", "-", "-", "-", "-"),
    ("pure black background", "#000000", "-", "-", "-", "-", "-"),
]

rows = ["# Generated by gen-shield-text-colors.py — do not edit by hand.",
        "# name\tbackground\ttitle\tsubtitle\tprimaryButton.backgroundColor\tprimaryButton.color\tsecondaryButton.color\t=> title\tsubtitle\tprimaryButton\tsecondaryButton"]
for name, *inputs in CASES:
    out = resolve(*[parse(i) for i in inputs])
    rows.append("\t".join([name, *inputs, "=>", *[hexa(c) for c in out]]))
    bg = parse(inputs[0])
    if bg and inputs[1] == "-":
        print("%-60s title %5.2f:1  subtitle %5.2f:1" % (name, contrast(out[0], bg), contrast(out[1], bg)))
open(__file__.replace("gen-shield-text-colors.py", "shield-text-colors.tsv"), "w").write("\n".join(rows) + "\n")
